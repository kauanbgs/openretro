// Builds public/play/games.json, the games of the web build (npm run
// build:play), from Homebrew Hub (hh.gbdev.io), the
// gbdev / gbadev / nesdev homebrew database. Only games whose license allows
// redistribution are kept. ROMs and covers are linked straight from the
// source repositories on raw.githubusercontent.com (which allows CORS), so
// nothing is rehosted. Every link is checked before it goes in the list.
//
//   node scripts/build-play-catalog.mjs

import { writeFile } from "node:fs/promises";

const OUT = new URL("../public/play/games.json", import.meta.url);

// Licenses that allow sharing the ROM as is.
const OPEN_LICENSE = /^(MIT|GPL|Zlib|FSFAP|CC-BY|MPL|Unlicense|0BSD|Apache|WTFPL)/i;
// Entries that are not really games, or that use third-party content.
const SKIP = new Set(["dd-character-sheet-demade", "piugba"]);
// Shown first, the rest follow by title.
const FEATURED = [
  "tobutobugirldeluxe", "apotris", "skyland", "novathesquirrel",
  "ucity-advance", "porklike-gb", "shock-lobster", "libbet", "aevilia", "minicraft-gba",
  "thwaite", "gbatris", "waternet", "the-hat-chooses-the-wizard", "deep-scan",
];

const PLATFORM = { GB: "gb", GBC: "gbc", GBA: "gba", NES: "nes" };
const BY_EXTENSION = { gb: "gb", gbc: "gbc", gba: "gba", nes: "nes" };

async function fetchAll() {
  const entries = [];
  for (let page = 1, total = 1; page <= total; page++) {
    const response = await fetch(`https://hh3.gbdev.io/api/search?page=${page}`);
    const data = await response.json();
    total = data.page_total;
    entries.push(...data.entries);
  }
  return entries;
}

function rawUrl(entry, file) {
  const repo = entry.baserepo.replace("https://github.com/", "");
  const path = `entries/${entry.slug}/${file}`.split("/").map(encodeURIComponent).join("/");
  return `https://raw.githubusercontent.com/${repo}/master/${path}`;
}

const exists = (url) =>
  fetch(url, { method: "HEAD" }).then((r) => r.ok, () => false);

function developerName(entry) {
  const d = entry.developer;
  if (!d) return undefined;
  if (typeof d === "string") return d;
  return d.map((p) => (typeof p === "string" ? p : p.name)).join(", ");
}

const entries = await fetchAll();
const seen = new Set();
const candidates = entries.filter((e) => {
  const license = e.gameLicense || e.license;
  if (seen.has(e.slug) || SKIP.has(e.slug)) return false;
  if (!license || !OPEN_LICENSE.test(license) || e.typetag !== "game") return false;
  if (!(e.files ?? []).some((f) => f.playable)) return false;
  seen.add(e.slug);
  return true;
});

const games = (
  await Promise.all(
    candidates.map(async (e) => {
      const file = e.files.find((f) => f.playable && f.default) ?? e.files.find((f) => f.playable);
      const extension = file.filename.split(".").pop().toLowerCase();
      const platform = PLATFORM[e.platform] ?? BY_EXTENSION[extension];
      if (!platform) return null;
      const rom = rawUrl(e, file.filename);
      const shot = e.screenshots.find((s) => /cover/i.test(s)) ?? e.screenshots[0];
      const cover = shot ? rawUrl(e, shot) : undefined;
      const [romOk, coverOk] = await Promise.all([exists(rom), cover ? exists(cover) : false]);
      // Gameplay images for the game page; the cover is usually the title screen.
      const screenshots = e.screenshots
        .filter((s) => s !== shot && /\.(png|jpe?g|gif|webp)$/i.test(s))
        .slice(0, 6)
        .map((s) => rawUrl(e, s));
      if (!romOk) {
        console.warn(`skip ${e.slug}: ROM not found`);
        return null;
      }
      // Dates are "YYYY", "YYYY-MM-DD" or, in a few entries, Unix seconds.
      const rawYear = Number.parseInt(e.date, 10);
      const year = rawYear > 3000 ? new Date(rawYear * 1000).getUTCFullYear() : rawYear;
      return {
        id: e.slug,
        title: e.title,
        platform,
        rom,
        ...(coverOk ? { cover } : {}),
        ...(screenshots.length ? { screenshots } : {}),
        ...(year > 1980 && year <= new Date().getFullYear() ? { year } : {}),
        developer: developerName(e),
        ...(e.description ? { description: e.description.split("\n\n")[0] } : {}),
        ...(e.tags?.length
          ? { genre: e.tags.filter((tag) => !/^open.?source$/i.test(tag)).slice(0, 2).join(", ") }
          : {}),
        license: e.gameLicense || e.license,
        source: e.repository || e.website?.[0] || e.website || `https://hh.gbdev.io/game/${e.slug}`,
      };
    }),
  )
).filter(Boolean);

const rank = (g) => {
  const i = FEATURED.indexOf(g.id);
  return i === -1 ? FEATURED.length : i;
};
games.sort((a, b) => rank(a) - rank(b) || a.title.localeCompare(b.title));

await writeFile(
  OUT,
  `${JSON.stringify(
    {
      about:
        "Homebrew games with open licenses, from Homebrew Hub (hh.gbdev.io). Generated by scripts/build-play-catalog.mjs.",
      games,
    },
    null,
    2,
  )}\n`,
);
console.log(`${games.length} games written to ${OUT.pathname}`);
