export function validatePartyServer(value: string) {
  const url = new URL(value);
  if (
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    url.pathname !== "/"
  )
    throw new Error("Use apenas o endereço do servidor, sem caminho ou senha.");
  if (
    url.protocol !== "https:" &&
    !(
      url.protocol === "http:" &&
      ["localhost", "127.0.0.1"].includes(url.hostname)
    )
  )
    throw new Error(
      "Use HTTPS. HTTP só é permitido em localhost para desenvolvimento.",
    );
  return url;
}
